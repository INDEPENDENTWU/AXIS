import assert from 'node:assert/strict';
import {compilePlayableSpec,assertPlayableSpec,PLAYABLE_SPEC_SCHEMA} from '../lib/axis-playable.mjs';

const native={id:'chest-row',baseId:'row',name:'划船',metricSchema:{metrics:['weight','reps']}};
const custom={id:'custom-identity-proof',name:'划船',metricSchema:{metrics:['duration']}};
const old={id:'row',name:'Generic historical row',metricSchema:{metrics:['completed']}};
const objects=[native,custom,old];
const original=JSON.stringify(objects);
const first=compilePlayableSpec({playableId:'native',source:{kind:'object',objectId:'chest-row'},objects});
const second=compilePlayableSpec({playableId:'custom',source:{kind:'object',objectId:'custom-identity-proof'},objects});
assert.equal(first.schema,PLAYABLE_SPEC_SCHEMA);
assert.equal(first.steps[0].objectRef,'chest-row');
assert.equal(second.steps[0].objectRef,'custom-identity-proof');
assert.notEqual(first.steps[0].objectRef,second.steps[0].objectRef);
assert.equal(JSON.stringify(objects),original,'compiler mutated caller Objects');
assert(Object.isFrozen(first)&&Object.isFrozen(first.steps[0]));
assert.equal(assertPlayableSpec(first).steps[0].objectRef,'chest-row');
assert.equal(JSON.stringify(compilePlayableSpec({playableId:'native',source:{kind:'object',objectId:'chest-row'},objects})),JSON.stringify(first));
const flow={schema:'axis.flow.v1',id:'flow-1',steps:[{id:'s1',objectRef:'chest-row',repeat:2},{id:'s2',objectRef:'custom-identity-proof',executionOverride:'timed'}]};
const flowCopy=JSON.stringify(flow);
const spec=compilePlayableSpec({playableId:'from-flow',source:{kind:'flow',flow},objects});
assert.deepEqual(spec.steps.map(x=>x.objectRef),['chest-row','custom-identity-proof']);
assert.deepEqual(spec.steps.map(x=>x.repeat),[2,1]);
assert.equal(spec.steps[1].executionMode,'timed');
assert.equal(JSON.stringify(flow),flowCopy);
const reject=(cb,label)=>assert.throws(cb,Error,label);
reject(()=>compilePlayableSpec({playableId:'wrong',source:{kind:'object',objectId:'nonexistent'},objects}),'no invented Object');
reject(()=>compilePlayableSpec({playableId:'wrong',source:{kind:'object',objectId:'row-family'},objects}),'no baseId fallback');
reject(()=>compilePlayableSpec({playableId:'bad',source:{kind:'object',objectId:'chest-row',script:'alert(1)'},objects}),'reject executable field');
reject(()=>compilePlayableSpec({playableId:'bad',source:{kind:'flow',flow:{...flow,steps:[flow.steps[0],flow.steps[0]]}},objects}),'duplicate steps');
reject(()=>compilePlayableSpec({playableId:'bad',source:{kind:'flow',flow:{...flow,steps:Array.from({length:33},(_,i)=>({id:'s'+i,objectRef:'chest-row'}))}},objects}),'bounded steps');
reject(()=>compilePlayableSpec({playableId:'bad',source:{kind:'object',objectId:'chest-row'},objects,heading:'<script>'}),'inert heading');
reject(()=>assertPlayableSpec({...first,schema:'axis.playable.v2'}),'reject future schema');
reject(()=>assertPlayableSpec({...first,script:'arbitrary code'}),'reject untrusted field');
reject(()=>compilePlayableSpec({playableId:'bad',source:{kind:'object',objectId:'chest-row'},objects:[native,{...native}]}),'duplicate Object');
assert.equal(original,JSON.stringify(objects),'historical generic Object was mutated');
console.log('[AXIS 8.31a PlayableSpec] PASS · native/custom same-name IDs distinct · exact Object/Flow source · immutable derived schema · invalid input rejects · bounded portable envelope · no second Encounter/Active owner');
