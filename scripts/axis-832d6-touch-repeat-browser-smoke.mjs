import assert from 'node:assert/strict';
import {chromium,webkit} from 'playwright';
const engine=process.env.AXIS_ENGINE||'chromium',base=process.env.AXIS_URL||'http://127.0.0.1:4173';
const browser=await (engine==='webkit'?webkit:chromium).launch(engine==='chromium'?{headless:true,args:['--no-sandbox']}:{headless:true});
const context=await browser.newContext({viewport:{width:360,height:780},deviceScaleFactor:2,hasTouch:true,isMobile:engine==='webkit',locale:'zh-CN',reducedMotion:'reduce'});
const page=await context.newPage(),errors=[];
page.on('pageerror',e=>errors.push(String(e)));
for(const [pat,val] of [['**/api/ai-status**',{available:false}],['**/api/owner-config**',{ok:true}],['**/api/analyze**',{available:false}],['**/api/insight**',{available:false}],['**/api/cloud-status**',{cloud:{configured:false,enabled:false}}],['**/api/ai-capabilities**',{ai:{enabled:false,capabilities:{}}}]])await page.route(pat,r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(val)}));
const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('axis_v60_state')||'{}'));
try{
 await page.goto(base,{waitUntil:'domcontentloaded'});
 await page.evaluate(()=>{localStorage.clear();localStorage.setItem('axis_v60_state',JSON.stringify({version:60,sessions:[],active:null,flows:[],flowRun:null,profile:{customEq:[],memories:[]},prefs:{scanSeconds:3}}));localStorage.setItem('axis_v8_meta',JSON.stringify({events:{},prefs:{}}))});
 await page.reload({waitUntil:'domcontentloaded'});await page.waitForFunction(()=>window.__AXIS_CORE_INTERACTIVE__===true&&window.__AXIS_832_PLAY_THIS__,undefined,{timeout:20000});
 assert.equal(await page.evaluate(()=>window.__AXIS_OPEN_EQUIPMENT_PICKER__?.('quick')),true);
 await page.locator('#eqSearch').fill('胸托划船');
 const button=page.locator('#v8710Cards .axis832ObjectGo[data-axis832-object="chest-row"]').first();
 await button.waitFor({state:'visible',timeout:6000});
 const box=await button.boundingBox();assert.ok(box&&box.width>=44&&box.height>=44);
 const x=box.x+box.width/2,y=box.y+box.height/2;
 const before=await state();
 const firstTouchStartedAt=Date.now();
 await page.touchscreen.tap(x,y);
 await page.waitForFunction(()=>document.querySelector('#scanSheet')?.classList.contains('show'),undefined,{timeout:7000});
 const afterFirst=await state();
 assert.deepEqual((afterFirst.active?.events||[]).map(e=>e.id),(before.active?.events||[]).map(e=>e.id),'P11 first touch tap forged Encounter');
 const secondTouchStartedAt=Date.now();
 await page.touchscreen.tap(x,y);
 await page.waitForTimeout(220);
 const afterSecond=await state();
 const visual=await page.evaluate(()=>({recorder:document.querySelector('#scanSheet')?.classList.contains('show'),pick:document.querySelector('#eqSheet')?.classList.contains('show'),owners:document.querySelectorAll('[data-axis-capture-owner]').length,recorders:document.querySelectorAll('#scanSheet').length,selected:window.__AXIS_SELECTED_EQUIPMENT__?.()?.id,focusInRecorder:document.querySelector('#scanSheet')?.contains(document.activeElement)}));
 console.log('P11_TOUCH_DOUBLE',JSON.stringify({engine,browser:browser.version(),firstToSecondTouchMs:secondTouchStartedAt-firstTouchStartedAt,visual}));
 assert.deepEqual((afterSecond.active?.events||[]).map(e=>e.id),(before.active?.events||[]).map(e=>e.id),'P11 rapid double touch manufactured a confirmed Encounter');
 assert.equal(afterSecond.flowRun||null,before.flowRun||null,'P11 Object double touch forged FlowRun');
 assert.equal(visual.recorders,1,'P11 dual tap created a second Recorder');
 assert.equal(visual.owners,1,'P11 double touch created competing capture owner');
 assert.equal(visual.recorder,true,'P11 second touch closed original Recorder');
 assert.equal(visual.pick,false,'P11 picker still obscures Recorder');
 assert.equal(visual.selected,'chest-row','P11 double touch lost exact Object identity');
 await page.locator('#scanSheet [data-close="scanSheet"]').first().click();
 assert.deepEqual((await state()).active?.events||[],before.active?.events||[],'P11 cancellation after fast touch created history');
 assert.deepEqual(errors,[],'browser runtime exceptions');
 console.log('[AXIS 8.32 P11 '+engine+'] PASS · real touchscreen double tap · one original Recorder/capture owner · no duplicate fact · cancel pure');
}finally{await browser.close()}
